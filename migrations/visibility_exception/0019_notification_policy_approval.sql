-- 通知策略补发布批准责任（`PAR-VIS-07`）。
--
-- 登记口对五类目录一律要求版本、适用范围与发布批准责任三样。另外四类建表时就带了
-- approved_by（0009 的映射与分诊两份、0011 的索赔声明、0012 的披露策略、0018 的授权
-- 目录），通知策略是唯一缺的一处——而 `PAR-VIS-07` 恰恰把批准摆在中心：「默认草稿经
-- 授权确认，严格范围才可自动发布」。没有这一列，登记一条自动发布的渠道与时限就查不
-- 出是谁批的，「通知义务不得由消息提交或渠道接受推定」在追溯上便无处落脚。
--
-- 不补版本表，也不补有效区间：0010 已论证这份目录没有「配了但这条没命中」那第二格，
-- 版本化由键里的披露策略引用承担，同一策略换版换的是引用值、新旧两行并存。那条理由
-- 不因本迁移改变，本迁移只加批准责任一列。
--
-- ADD COLUMN NOT NULL 无默认（照 0003 与 0014）：表在测试库与 CI 上是空的（登记口
-- 之前非测试写入为零）；有行却填不出批准责任就让迁移失败，禁止填占位批准人——那会
-- 把「还没人批」伪装成一次已经作出的批准。

ALTER TABLE visibility_exception.notification_policy
    ADD COLUMN approved_by text NOT NULL,
    ADD CONSTRAINT notification_policy_approved_by_not_blank
        CHECK (btrim(approved_by) <> '');
