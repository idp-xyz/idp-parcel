package ports

import (
	"context"

	"go.idp.xyz/idp-parcel/internal/parcelshipment/domain"
)

// PreAcceptanceControlScopeLock 在保存委托之前取接受前资金控制所在作用域的那把锁。锁是 settlement-accounting 的
// `ports.PreAcceptanceControlScopeLock`（S，施加与释放控制都取，键是租户加结算作用域，事务级、随事务结束放）；本端口只把
// 控制结果上存下的占用作用域交给它，本上下文不解释任何一段。
//
// 为什么要在保存委托之前取：同一事务里既写委托行（R，保存委托的 UPDATE）又要取 S 的路径，必须全部先 S 后 R。接受链先走
// 财务控制（freezeFunds 先取 S），再在形成决定时保存委托；撤回、主动拒绝、授权处置若先保存委托、再在释放里取 S，同一份委托
// 并发时一笔持 S 等 R、一笔持 R 等 S，PostgreSQL 的死锁检测中止其中一笔。S 是（租户，作用域）级、R 是一份委托，两笔必须是
// 同一份委托才成环。
//
// 锁序（同一事务里的取锁次序，往里加任何一把锁先回头核这条全序）：消费门认领 inbox 行（仅 parcel-dispatch）→ S（按「一笔事务
// 取多把 S 时」那一段的版本次序，可有若干把）→ R（保存委托）→ 其后的行写入与 outbox 插入。各路径：
//
//   - 接受链：链开头放被取代各版（取各自存下的作用域的 S）→ 施加当前版本的控制（取其 S）→ 形成决定保存委托（R）→ 拒绝或
//     停进等待受控补充之后的释放。R 之后取的 S 都是此前已持有的，重入不等待。
//   - 撤回、主动拒绝、授权处置：保存委托之前先取齐这份委托各版已成立占用所在作用域的 S（本端口），再保存委托（R），再释放。
//     接受链自动拒绝与停进等待受控补充的保存之前同样先取（形成决定一支，接受链里是重入）。
//   - 已越过提交边界的委托（撤回的重放，或来源身份头一次到达一份已决的委托，读回既有决定）不保存委托，只在释放里取 S，
//     不持 R，不需要先取。
//   - 接受链形成决定处读到已撤回或已拒绝（不是本轮形成）的委托：不保存委托，只在逐版放占用之前按同一次序取齐各版的 S（本
//     端口；链里是重入），不持 R，所以与接受链、撤回类路径之间不成环。链读到`已提交`之后撤回、拒绝抢先提交时，链这一轮占下的冻结靠这一步
//     在链自己的事务里放掉。
//   - 取消边界锁 P（ports.CancellationBoundaryLock）不与 S、R 同时持有：取消、采用、终局三处不更新委托行，不取 S；持 S 的
//     事务不取 P。委托提交守卫的来源身份锁同理，提交路径不取 S。
//
// 一笔事务取多把 S 时（一份委托的各版在不同作用域形成占用）按版本形成顺序：被取代各版在前、当前版本在后，与接受链开头放
// 被取代各版、再施加当前版本的次序一致，所以同一份委托上链与撤回类路径之间 S 也不成环。不同委托的各版若在同一对作用域上
// 次序相反，S 与 S 之间仍可成环——施加当前版本的作用域要到施加时才形成，取不出一个先验的全序；它要各版作用域不同才出现。
//
// 没有存下作用域、或没有成立占用的版本不取：释放那一侧本来就不会为它碰账本。取不到锁与保存委托失败落同一格，不当作释放
// 放不掉：这一步还在保存委托之前，业务事实尚未形成。形成决定处在已终结的委托上取不到锁时没有委托要保存，落`释放未收口`：
// 不放，交回未决让这一轮回滚。
type PreAcceptanceControlScopeLock interface {
	LockControlScope(ctx context.Context, tenant domain.TenantID, scope domain.OccupationScope) error
}
